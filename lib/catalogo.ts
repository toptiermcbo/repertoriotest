// Helper para parsear valores como "1,43 GB", "875 MB", "1935" (MB suelto), etc.
// y devolver siempre un número en MB.
function parseMb(raw: string | number): number {
  if (typeof raw === 'number') return raw
  const s = String(raw).trim()
  // "X,XX GB" o "X.XX GB"
  const gbMatch = s.match(/([\d,.]+)\s*GB/i)
  if (gbMatch) return parseFloat(gbMatch[1].replace(',', '.')) * 1024
  // "XXX MB"
  const mbMatch = s.match(/([\d,.]+)\s*MB/i)
  if (mbMatch) return parseFloat(mbMatch[1].replace(',', '.'))
  // número puro
  const n = parseFloat(s.replace(',', '.'))
  return isNaN(n) ? 0 : n
}

